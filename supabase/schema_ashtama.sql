-- ============================================================
-- 1. MOON DAILY
--    Stores pre-computed Moon longitude + nakshatra per date/location.
--    Shared lookup used by Tara + Ashtama engines.
-- ============================================================
CREATE TABLE IF NOT EXISTS moon_daily (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    date            DATE NOT NULL,
    location_name   TEXT NOT NULL,
    moon_longitude  DOUBLE PRECISION NOT NULL,   -- sidereal (Lahiri)
    moon_rasi_index INTEGER NOT NULL,            -- 0–11
    moon_nak_index  INTEGER NOT NULL,            -- 0–26
    moon_nak_name   TEXT NOT NULL,
    moon_pada       INTEGER NOT NULL,            -- 1–4
    moon_sign       TEXT NOT NULL,
    calculated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(date, location_name)
);

CREATE INDEX IF NOT EXISTS moon_daily_date_loc_idx ON moon_daily(date, location_name);

