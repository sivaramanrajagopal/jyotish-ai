-- ============================================================
-- 4. USER DAILY PANCHANGAM
--    Personalised daily record per user: Tara + Ashtama + Chandrabalam.
--    Generated by the 04:30 AM scheduler job.
-- ============================================================
CREATE TABLE IF NOT EXISTS user_daily_panchangam (
    id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id              UUID NOT NULL,          -- no FK until auth is wired up
    date                 DATE NOT NULL,

    -- Tara Balam
    tara_position        INTEGER NOT NULL,        -- 1–9
    tara_name            TEXT NOT NULL,
    tara_nature          TEXT NOT NULL,           -- benefic | malefic | neutral
    tara_colour          TEXT NOT NULL,           -- green | red | yellow
    tara_meaning         TEXT NOT NULL,

    -- Chandra Ashtama
    is_chandra_ashtama   BOOLEAN NOT NULL DEFAULT FALSE,
    ashtama_start        TIMESTAMPTZ,
    ashtama_end          TIMESTAMPTZ,
    next_ashtama_date    DATE,                    -- when not currently active

    -- Chandrabalam
    chandrabalam_good    BOOLEAN NOT NULL DEFAULT TRUE,
    moon_house_from_natal INTEGER NOT NULL,       -- 1–12 (Moon's current house counted from natal Moon rasi)

    -- Context
    natal_moon_nak       TEXT NOT NULL,
    natal_moon_rasi      TEXT NOT NULL,
    today_moon_sign      TEXT NOT NULL,
    today_moon_nak       TEXT NOT NULL,

    calculated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE(user_id, date)
);

CREATE INDEX IF NOT EXISTS udp_user_date_idx ON user_daily_panchangam(user_id, date DESC);

-- ============================================================
-- 5. ASHTAMA ALERTS
--    Push notification log for Chandra Ashtama events.
-- ============================================================
CREATE TABLE IF NOT EXISTS ashtama_alerts (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id      UUID NOT NULL,
    alert_date   DATE NOT NULL,
    alert_type   TEXT NOT NULL CHECK (alert_type IN ('start', 'end', 'reminder')),
    message      TEXT NOT NULL,
    sent_at      TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(user_id, alert_date, alert_type)
);

-- ============================================================
-- 6. USER LOCATIONS
--    Current location override per user (for Panchangam calculation).
--    Defaults to the birth location if not set.
-- ============================================================
CREATE TABLE IF NOT EXISTS user_locations (
    user_id    UUID PRIMARY KEY,
    city       TEXT NOT NULL,
    lat        DOUBLE PRECISION NOT NULL,
    lon        DOUBLE PRECISION NOT NULL,
    timezone   TEXT NOT NULL DEFAULT 'Asia/Kolkata',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================
-- RLS — match existing pattern
-- ============================================================
ALTER TABLE moon_daily             ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_daily_panchangam  ENABLE ROW LEVEL SECURITY;
ALTER TABLE ashtama_alerts         ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_locations         ENABLE ROW LEVEL SECURITY;
ALTER TABLE tara_lookup            ENABLE ROW LEVEL SECURITY;
ALTER TABLE ashtama_lookup         ENABLE ROW LEVEL SECURITY;

-- Public read for static lookup tables
CREATE POLICY "tara_lookup_public_read"    ON tara_lookup    FOR SELECT USING (true);
CREATE POLICY "ashtama_lookup_public_read" ON ashtama_lookup FOR SELECT USING (true);

-- moon_daily: service role writes, public reads (shared across users)
CREATE POLICY "moon_daily_public_read"     ON moon_daily FOR SELECT USING (true);
CREATE POLICY "moon_daily_service_write"   ON moon_daily FOR ALL USING (auth.role() = 'service_role');

-- Per-user tables: service role writes (scheduler), users read own rows
CREATE POLICY "udp_service_write"  ON user_daily_panchangam FOR ALL USING (auth.role() = 'service_role');
CREATE POLICY "alerts_service_write" ON ashtama_alerts      FOR ALL USING (auth.role() = 'service_role');
CREATE POLICY "locations_service_write" ON user_locations   FOR ALL USING (auth.role() = 'service_role');

-- Also add moon_nakshatra_index + moon_rasi_index columns to natal_charts if not present
ALTER TABLE natal_charts
    ADD COLUMN IF NOT EXISTS moon_nakshatra_index INTEGER,
    ADD COLUMN IF NOT EXISTS moon_rasi_index      INTEGER;
